/*
 * gen-ui-resources.mjs — desktop-only UI bundler.
 *
 * Root is this desktop source folder, so the desktop exe never reads the web
 * app's js/ tree.  Edit the snapshot under src/ui/ for desktop changes.
 *
 * Run:  node tools/gen-ui-resources.mjs
 * Out:  shell/ui_resources.cpp / .h
 */
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from 'node:fs';
import { join, dirname, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const srcRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(srcRoot, 'shell');
const outFile = join(outDir, 'ui_resources.cpp');
mkdirSync(outDir, { recursive: true });

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.mjs': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.bmp': 'image/bmp',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.ttf': 'font/ttf',
  '.woff': 'font/woff',
  '.jpg': 'image/jpeg',
  '.wasm': 'application/wasm',
  '.woff2': 'font/woff2'
};

const uiRoot = join(srcRoot, 'ui');

/* Walk the whole snapshot instead of listing one directory.
 *
 * The ES-module graph has subdirectories: js/wgpu/ (the perturbation engine)
 * and js/vendor/ (gmp-wasm).  A generator that only globbed `js/*.js` built a
 * table without them, so the page's first import 404'd, the module graph never
 * evaluated, and the window sat on its boot watchdog for nine seconds with
 * "core scripts failed to load" — while the resource handler was happily
 * answering 200 for the 32 files it did know.  Discover, do not enumerate. */
const SKIP_DIRS = new Set(['.git', 'node_modules']);
function walk(rel) {
  const out = [];
  let names;
  try {
    names = readdirSync(join(uiRoot, rel), { withFileTypes: true });
  } catch {
    return out;
  }
  names.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const d of names) {
    const child = rel ? rel + '/' + d.name : d.name;
    if (d.isDirectory()) {
      if (!SKIP_DIRS.has(d.name)) out.push(...walk(child));
    } else if (extname(d.name) && MIME[extname(d.name).toLowerCase()]) {
      out.push(child);
    }
  }
  return out;
}
const files = walk('');
/* index.html first: it is the document the shell navigates to. */
files.sort((a, b) => (a === 'index.html' ? -1 : b === 'index.html' ? 1 : 0));

const entries = [];
const chunks = [];
let total = 0;

function bytesLiteral(buf, name) {
  const lines = [`static const unsigned char ${name}[] = {`];
  let line = '  ';
  for (let i = 0; i < buf.length; i++) {
    line += '0x' + buf[i].toString(16).padStart(2, '0') + ',';
    if (line.length > 108) { lines.push(line); line = '  '; }
  }
  if (line.trim()) lines.push(line);
  lines.push('};');
  return lines.join('\n');
}

files.forEach((rel, i) => {
  const full = join(uiRoot, rel);
  let st;
  try { st = statSync(full); } catch { console.warn('[ui-res] skip missing ' + rel); return; }
  if (!st.isFile()) return;
  const buf = readFileSync(full);
  total += buf.length;
  const name = `ui_${i}`;
  chunks.push(bytesLiteral(buf, name));
  entries.push(`  { "${rel.replace(/\\/g, '/')}", ${name}, ${buf.length}u, "${MIME[extname(rel)] || 'application/octet-stream'}" },`);
});

writeFileSync(join(outDir, 'ui_resources.h'), `// Generated by tools/gen-ui-resources.mjs — do not edit.
#pragma once

struct UiFile {
  const char* path;
  const unsigned char* data;
  unsigned size;
  const char* mime;
};

extern const UiFile kUiFiles[];
extern const unsigned kUiFileCount;
`);

writeFileSync(outFile, `// Generated by tools/gen-ui-resources.mjs — do not edit.
#include "ui_resources.h"
#include <cstdint>

${chunks.join('\n\n')}

const UiFile kUiFiles[] = {
${entries.join('\n')}
};

const unsigned kUiFileCount = ${entries.length}u;
`);

console.log(`[ui-res] ${entries.length} files, ${(total / 1024).toFixed(1)} KB -> ${relative(srcRoot, outFile)}`);
